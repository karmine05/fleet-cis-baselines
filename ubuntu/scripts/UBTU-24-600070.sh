#!/bin/sh
# UBTU-24-600070: Must disable kernel core dumps so that it can fail to a secure state if system initialization fails, shutdown fails or aborts fail
# Fleet policy: CIS 1.103 UBTU-24-600070 (Automated)
# Usage: $0 [--check|--apply]  --check: exit 0 = compliant, 1 = not compliant (read-only). --apply: remediate, then re-check.
# Fleet runs scripts without arguments, so DEFAULT_MODE decides what a Fleet run does. Set it to --apply only for a remediation run.
DEFAULT_MODE=--check
[ "$(id -u)" -eq 0 ] || { echo "run as root"; exit 2; }



check() (
  ! systemctl is-enabled --quiet kdump-tools.service 2>/dev/null && ! systemctl is-active --quiet kdump-tools.service
)

apply() {
  systemctl disable --now kdump-tools.service
}

case "${1:-$DEFAULT_MODE}" in
  --check) if check; then echo COMPLIANT; exit 0; else echo NOT_COMPLIANT; exit 1; fi ;;
  --apply)
    if check; then echo "already compliant"; exit 0; fi
    apply || { echo "apply step failed"; exit 1; }
    if check; then echo REMEDIATED; exit 0; else echo "still not compliant"; exit 1; fi ;;
  *) echo "usage: $0 [--check|--apply]"; exit 2 ;;
esac
